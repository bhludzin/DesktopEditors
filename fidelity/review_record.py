#!/usr/bin/env python3
"""Writes the discrepancy specs from reviewed findings and the issue tracker.

    python fidelity/review_record.py <deck-dir> <specs-dir>

Reads <deck-dir>/review/discrepancies.json (from review_merge.py) and
<specs-dir>/issues.json, the tracker (from review_issues.py, then edited by hand):
  {"issues": [{"id": "I-007", "title": ..., "severity": "major|minor|trivial",
               "status": "open|in-progress|fixed|wontfix|not-a-bug", "fixed_in": null,
               "categories": [...], "description", "powerpoint", "euro_office",
               "suspected_cause", "code_area", "fix_idea", "confidence",
               "findings": ["S0297-1", ...],   # findings that belong to it
               "tag": "K2" | null,              # slide-level known-issue tag it also covers
               "representative": [...], "merged_from": [...], "doubts": [...],
               "log": [{"date": ..., "note": ...}]}],
   "rejected": [{"id": "S0123-1", "reason": ...}]}
Writes into <specs-dir>:
  findings.json      every reviewed slide and finding, each finding stamped with its issue
  issues/README.md   the issues by status and severity
  issues/<id>.md     one spec per issue: what differs, PowerPoint's rule, cause, code, fix, slides
  slides.md          every slide that differs, with its issues
Slide sheets and crops stay in <deck-dir>/review and are linked from there.
Edit the tracker (status, fixed_in, log) and re-run this to refresh the pages.
"""
import collections
import json
import os
import sys
from pathlib import Path

SEV_ORDER = {'major': 0, 'minor': 1, 'trivial': 2}
STATUS_ORDER = {'in-progress': 0, 'open': 1, 'fixed': 2, 'wontfix': 3, 'not-a-bug': 4}
SECTIONS = (('What differs', 'description'), ('What PowerPoint does', 'powerpoint'), ('What Euro-Office does', 'euro_office'),
            ('Suspected cause', 'suspected_cause'), ('Where to look', 'code_area'), ('Fix idea', 'fix_idea'))


def one_line(text, limit=None):
    text = ' '.join(str(text or '').split()).replace('|', '/')
    return text if limit is None or len(text) <= limit else text[:limit - 1] + '…'


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    review, specs = Path(sys.argv[1]) / 'review', Path(sys.argv[2])
    record = json.loads((review / 'discrepancies.json').read_text(encoding='utf-8'))
    tracker = json.loads((specs / 'issues.json').read_text(encoding='utf-8'))
    issues, rejected = tracker['issues'], {r['id']: r.get('reason') for r in tracker.get('rejected', [])}

    findings = {f['id']: (s['slide'], f) for s in record['slides'] for f in s.get('findings', [])}
    owner, problems = {}, []
    for i in issues:
        for fid in i.get('findings', []):
            if fid not in findings:
                problems.append(f'{i["id"]}: unknown finding {fid}')
            elif fid in owner:
                problems.append(f'{fid} is in both {owner[fid]} and {i["id"]}')
            else:
                owner[fid] = i['id']
    unassigned = sorted(set(findings) - set(owner) - set(rejected))
    for fid, (_, f) in findings.items():
        f['issue'] = owner.get(fid)
        if fid in rejected:
            f['status'], f['rejected_reason'] = 'rejected', rejected[fid]
    (specs / 'findings.json').write_text(json.dumps(record, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')

    def sheet(n, from_dir):
        return Path(os.path.relpath(review / 'sheets' / f'p{n:04d}.png', from_dir)).as_posix()

    def crops(n, from_dir):
        return [(p.name, Path(os.path.relpath(p, from_dir)).as_posix()) for p in sorted((review / 'crops').glob(f'{n:04d}-*.png'))]

    tag_slides = collections.defaultdict(set)
    for s in record['slides']:
        for k in s.get('known', []):
            tag_slides[k.get('id')].add(s['slide'])
    by_slide = collections.defaultdict(set)
    for i in issues:
        i['_finding_slides'] = {findings[fid][0] for fid in i.get('findings', []) if fid in findings}
        i['_slides'] = i['_finding_slides'] | (tag_slides.get(i['tag'], set()) if i.get('tag') else set())
        for n in i['_slides']:
            by_slide[n].add(i['id'])
    issues.sort(key=lambda i: (STATUS_ORDER.get(i.get('status', 'open'), 9), SEV_ORDER.get(i.get('severity'), 9),
                               -len(i['_slides']), i['id']))

    out = specs / 'issues'
    out.mkdir(exist_ok=True)
    for old in out.glob('*.md'):
        old.unlink()
    verdicts = collections.Counter(s.get('verdict') for s in record['slides'])
    md = ['# Discrepancy issues', '',
          f'Generated by `fidelity/review_record.py` from [`../issues.json`](../issues.json) (the tracker) and '
          f'[`../findings.json`](../findings.json); edit the tracker, not this page. Review of run `{record["run"]}`: '
          f'{record["slides_reviewed"]} of {record["slides_total"]} slides, {verdicts.get("match", 0)} match apart from '
          f'known sub-pixel noise, {verdicts.get("differs", 0)} differ. {len(findings)} findings: '
          f'{len(findings) - len(rejected)} in {len(issues)} issues, {len(rejected)} rejected on a second look.', '']
    if problems or unassigned:
        md += ['> **Tracker problems:** ' + '; '.join(problems + [f'{len(unassigned)} findings in no issue: '
                                                                + ', '.join(unassigned[:30])]), '']
    md += ['| Issue | Status | Severity | Slides | Findings | Title |', '|---|---|---|---:|---:|---|']
    for i in issues:
        md.append(f'| [{i["id"]}]({i["id"]}.md) | {i.get("status", "open")} | {i.get("severity", "")} | '
                  f'{len(i["_slides"])} | {len(i.get("findings", []))} | {one_line(i["title"])} |')
    if rejected:
        md += ['', '## Rejected findings', '', 'A second look judged these not to be real Euro-Office differences.', '']
        md += [f'- {fid} (slide [{findings[fid][0]}]({sheet(findings[fid][0], out)})): {one_line(why)}'
               for fid, why in sorted(rejected.items()) if fid in findings]
    (out / 'README.md').write_text('\n'.join(md) + '\n', encoding='utf-8')

    for i in issues:
        n_tag = len(i['_slides'] - i['_finding_slides'])
        doc = [f'# {i["id"]}: {one_line(i["title"])}', '',
               '| | |', '|---|---|',
               f'| Status | {i.get("status", "open")}' + (f' (fixed in {i["fixed_in"]})' if i.get('fixed_in') else '') + ' |',
               f'| Severity | {i.get("severity", "")} |',
               f'| Slides | {len(i["_slides"])}' + (f' ({n_tag} of them only through the slide tag {i["tag"]})' if n_tag else '') + ' |',
               f'| Findings | {len(i.get("findings", []))} |',
               f'| Categories | {", ".join(i.get("categories", []))} |',
               f'| Confidence in the cause | {i.get("confidence", "")} |', '']
        for label, key in SECTIONS:
            if i.get(key):
                doc += [f'## {label}', '', str(i[key]).strip(), '']
        if i.get('merged_from'):
            doc += ['## Also covers', '', 'Issues found separately that share this cause:', '']
            for m in i['merged_from']:
                doc.append(f'- {one_line(m.get("title"))}' + (f' (code: {one_line(m["code_area"])})' if m.get('code_area') else ''))
            doc.append('')
        if i.get('doubts'):
            doc += ['## Open questions', ''] + [f'- {one_line(d)}' for d in i['doubts']] + ['']
        doc += ['## How to verify', '',
                'Build and render with `python fidelity/fidelity.py loop <deck> --label <name>`, then rebuild the review '
                'facts with `python fidelity/review_prep.py <deck-dir> <name>` and look at the slides below: their findings '
                'should be gone, and no other slide should lose line-break matches or SSIM against the previous run '
                '(`fidelity.py runs <deck>`). Then set `status` and `fixed_in` in `issues.json`, add a `log` entry, and '
                're-run `review_record.py`.', '']
        if i.get('log'):
            doc += ['## Log', ''] + [f'- {e.get("date", "")}: {one_line(e.get("note"))}' for e in i['log']] + ['']
        doc += ['## Slides', '']
        if i['_finding_slides']:
            doc.append('With findings: ' + ', '.join(f'[{n}]({sheet(n, out)})' for n in sorted(i['_finding_slides'])))
        if n_tag:
            tagged = sorted(i['_slides'] - i['_finding_slides'])
            doc.append('')
            doc.append(f'Tagged {i["tag"]} only ({len(tagged)}): ' + ', '.join(str(n) for n in tagged))
        doc.append('')
        if i.get('findings'):
            reps = set(i.get('representative', []))
            doc += ['## Findings', '', 'Full detail (measurements, XML, objects) is in `findings.json`. '
                    '★ marks the clearest examples.', '',
                    '| Finding | Slide | Object | Severity | Euro-Office | Crops |', '|---|---:|---|---|---|---|']
            for fid in i['findings']:
                if fid not in findings:
                    continue
                n, f = findings[fid]
                c = ' '.join(f'[{name}]({link})' for name, link in crops(n, out)[:3])
                doc.append(f'| {fid}{" ★" if fid in reps else ""} | [{n}]({sheet(n, out)}) | {one_line(f.get("object"))} | '
                           f'{f.get("severity", "")} | {one_line(f.get("euro_office") or f.get("detail"), 220)} | {c} |')
            doc.append('')
        (out / f'{i["id"]}.md').write_text('\n'.join(doc) + '\n', encoding='utf-8')

    rows = ['# Slides that differ', '',
            'Generated by `fidelity/review_record.py`. Every slide with a finding, and its issues '
            '(slide-wide tags for sub-pixel noise, K2/K4/K5/K6, are left out).', '',
            '| Slide | Issues | Summary |', '|---:|---|---|']
    for s in record['slides']:
        n = s['slide']
        ids = sorted({owner[f['id']] for f in s.get('findings', []) if f['id'] in owner})
        if ids:
            rows.append(f'| [{n}]({sheet(n, specs)}) | {", ".join(f"[{x}](issues/{x}.md)" for x in ids)} | '
                        f'{one_line(s.get("summary"))} |')
    (specs / 'slides.md').write_text('\n'.join(rows) + '\n', encoding='utf-8')

    print(f'{len(issues)} issues, {len(findings)} findings, {len(unassigned)} unassigned, {len(problems)} problems')
    for p in problems[:20]:
        print('PROBLEM', p)


if __name__ == '__main__':
    main()
